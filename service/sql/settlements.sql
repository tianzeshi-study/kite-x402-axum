CREATE TABLE IF NOT EXISTS kite_x402_settlement_v1 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network TEXT NOT NULL,
    asset TEXT NOT NULL,
    payer TEXT NOT NULL,
    pay_to TEXT NOT NULL,
    nonce TEXT NOT NULL,
    amount_atomic NUMERIC(78, 0) NOT NULL CHECK (amount_atomic > 0),
    state TEXT NOT NULL CHECK (state IN ('verifying', 'executing', 'upstream_failed',
        'settling', 'reported_success', 'confirmed', 'canceled', 'transfer_mismatch')),
    transaction_hash TEXT,
    scan_from BIGINT,
    next_check_at TIMESTAMPTZ,
    lease_until TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (network, asset, payer, nonce)
);
CREATE INDEX IF NOT EXISTS kite_x402_settlement_v1_pending
    ON kite_x402_settlement_v1 (next_check_at, id) WHERE state = 'settling';
CREATE INDEX IF NOT EXISTS kite_x402_settlement_v1_verifying
    ON kite_x402_settlement_v1 (lease_until, id) WHERE state = 'verifying';
CREATE INDEX IF NOT EXISTS kite_x402_settlement_v1_transaction
    ON kite_x402_settlement_v1 (network, transaction_hash, id) WHERE transaction_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS kite_x402_settlement_v1_recent
    ON kite_x402_settlement_v1 (updated_at DESC, id DESC) WHERE state <> 'verifying';
